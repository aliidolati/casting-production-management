-- =====================================================================
-- فیلد «مرحله» در عملیات حرارتی
--
-- روی محموله می‌نشیند نه روی قطعه، چون درست بعد از تاریخ در ردیف پارامترهای
-- سیکل قرار می‌گیرد و همه‌ی قطعات یک محموله در یک سیکل مشترک، یک مرحله را
-- می‌گذرانند.
--
-- نام ستون treatment_stage است تا با PieceStage (مرحله‌ی تولید قطعه) اشتباه
-- گرفته نشود؛ آن یکی وضعیت قطعه در خط تولید است، این یکی مرحله‌ی خودِ سیکل کوره.
--
-- ستون nullable است چون برای رکوردهای موجود مقدار پیش‌فرض معناداری وجود ندارد؛
-- در فرم ثبت اجباری است.
-- =====================================================================

ALTER TABLE heat_treatment_batches
    ADD COLUMN treatment_stage VARCHAR(50) NULL AFTER treatment_date;

-- گزارش تجمیعی بر حسب مرحله (مثلاً میانگین سختی تست پلیت به ازای هر مرحله)
CREATE INDEX idx_heat_treatment_batch_stage ON heat_treatment_batches (treatment_stage);
