-- =====================================================================
-- مرحله‌ی جدید «خشن‌تراشی» بین ذوب‌ریزی و رادیوگرافی
--
-- زیرمرحله‌ها: پلیسه‌گیری ← اصلاح اولیه ← تراش
--
-- این migration کاملاً غیرمخرب است و فقط یک ستون nullable اضافه می‌کند:
--   * pieces.current_stage از نوع VARCHAR(32) است، پس مقدار جدید ROUGH_MACHINING
--     به enum جاوا نیازی به تغییر ساختار ندارد.
--   * piece_sub_stage_history.kind هم VARCHAR(32) است، پس kind جدید بدون
--     تغییر اسکیما ثبت می‌شود و تاریخچه‌ی خشن‌تراشی در همان جدول مشترک می‌نشیند.
--
-- قطعات موجود مقدار NULL می‌گیرند، یعنی «هنوز وارد خشن‌تراشی نشده‌اند»؛ دقیقاً
-- همان رفتاری که ستون‌های radiography_sub_stage و heat_treatment_sub_stage دارند.
-- =====================================================================

ALTER TABLE pieces
    ADD COLUMN rough_machining_sub_stage VARCHAR(32) NULL AFTER heat_treatment_sub_stage;
