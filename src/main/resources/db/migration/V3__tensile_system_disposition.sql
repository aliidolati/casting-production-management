-- =====================================================================
-- تایید خودکار تست کشش توسط سیستم
--
-- وقتی همه‌ی نمونه‌های یک تست، همه‌ی حداقل پارامترهای تاییدیِ تعریف‌شده را
-- برآورده کنند، سیستم بدون دخالت کاربر تعیین‌تکلیف را با «مرحله بعدی = تایید»
-- و «نتیجه بازرسی = قبول» ثبت می‌کند. این ستون همان رکوردها را از
-- تعیین‌تکلیف‌های دستی جدا می‌کند تا در گزارش‌ها قابل تفکیک باشند.
--
-- next_stage و inspection_result از نوع VARCHAR هستند، پس اضافه‌شدن مقادیر
-- APPROVED و OTHER به enum جاوا نیازی به تغییر ساختار ندارد.
-- =====================================================================

ALTER TABLE tensile_test_dispositions
    ADD COLUMN system_generated BIT NOT NULL DEFAULT 0;

-- گزارش «چند درصد تاییدها خودکار بوده‌اند» روی این ستون فیلتر می‌زند
CREATE INDEX idx_tensile_disposition_system_generated
    ON tensile_test_dispositions (system_generated);
