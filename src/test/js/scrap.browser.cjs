const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');

(async () => {
    const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || '/usr/bin/chromium', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    const output = path.resolve(__dirname, '../../../target/scrap-browser');
    fs.mkdirSync(output, { recursive: true });
    const stored = () => page.evaluate(id => PieceAPI.getScrapDispatches(id), process.env.SCRAP_PIECE);
    const open = () => page.evaluate(id => openPieceProfile(id), process.env.SCRAP_PIECE);
    try {
        await page.goto(process.env.SCRAP_BASE);
        await page.locator('#input-login-username').fill(process.env.SCRAP_ADMIN);
        await page.locator('#input-login-password').fill(process.env.SCRAP_PASSWORD);
        await page.locator('#form-login button[type=submit]').click();
        await page.locator('#app-shell').waitFor({ state: 'visible' });
        await open();
        await page.locator('#btn-profile-scrap').click();
        await page.locator('#form-scrap-reason').waitFor();
        await page.locator('#nested-modal-close').click();
        await page.locator('#btn-profile-scrap:enabled').waitFor();
        assert.equal((await stored()).length, 0);
        await page.locator('#btn-profile-scrap').click();
        assert.deepEqual(await page.locator('#scrap-type option').evaluateAll(nodes => nodes.map(n => n.value).filter(Boolean)),
            ['F.M.M','F.M.L','F.M','S.P','S.C','CR','G.H','G.P','VT','C.S','M.R','ماسه ریزی','ابعادی','OTHER']);
        await page.locator('#scrap-type').selectOption('OTHER');
        await page.locator('#form-scrap-reason button[type=submit]').click();
        assert.match(await page.locator('#scrap-error').innerText(), /سایر/);
        await page.locator('#scrap-type').selectOption('ابعادی');
        await page.locator('#form-scrap-reason button[type=submit]').click();
        await page.locator('#btn-edit-scrap').waitFor();
        let history = await stored();
        assert.equal(history.length, 1);
        assert.equal(history[0].defectType, 'ابعادی');
        assert.equal(history[0].notes, '');
        const sent = history[0].sentAt;
        await page.setViewportSize({ width: 390, height: 844 });
        await page.locator('#btn-edit-scrap').click();
        assert.equal(await page.locator('#scrap-type').inputValue(), 'ابعادی');
        await page.locator('#scrap-type').selectOption('OTHER');
        await page.locator('#scrap-custom').fill('علت ساختگی <img src=x>');
        await page.locator('#scrap-notes').fill('توضیح قابل ویرایش');
        assert.equal(await page.locator('#form-scrap-reason').evaluate(el => el.scrollWidth > el.clientWidth + 2), false);
        const editResponse = page.waitForResponse(r => r.url().endsWith('/scrap-dispatch') && r.request().method() === 'PATCH');
        await page.locator('#form-scrap-reason button[type=submit]').click();
        assert.equal((await editResponse).status(), 200);
        await page.locator('#profile-scrap-section').getByText('علت ساختگی <img src=x>', { exact: true }).waitFor();
        history = await stored();
        assert.equal(history.length, 1);
        assert.equal(history[0].sentAt, sent);
        assert.equal(history[0].defectTypeCustom, 'علت ساختگی <img src=x>');
        assert.equal(await page.locator('#profile-scrap-section img').count(), 0);
        await page.evaluate(async id => { await PieceAPI.delete(id); await openPieceProfile(id); }, process.env.SCRAP_PIECE);
        assert.equal(await page.locator('#btn-edit-scrap').count(), 0);
        assert.match(await page.locator('#profile-scrap-section').innerText(), /علت ساختگی/);
        await page.evaluate(() => closeModal());
        await page.setViewportSize({ width: 1440, height: 1000 });
        await page.locator('#nav-btn-dashboard').click();
        await page.locator('#dashboard-tab-btn-reports').click();
        await page.locator('#dashboard-reports-menu [data-tab="scrap-report"]').click();
        await page.locator(`#scrap-report-project option[value="${process.env.SCRAP_PROJECT}"]`).waitFor({ state: 'attached' });
        await page.locator('#scrap-report-project').selectOption(process.env.SCRAP_PROJECT);
        await page.locator('#btn-scrap-report-run').click();
        await page.locator('#btn-scrap-report-export:enabled').waitFor();
        assert.equal(await page.locator('.scrap-report-row').count(), 2);
        const report = await page.locator('#scrap-report-table-body').innerText();
        assert.match(report, /علت ساختگی/);
        assert.match(report, /ثبت نشده/);
        assert.match(report, /بایگانی‌شده/);
        const downloadEvent = page.waitForEvent('download');
        await page.locator('#btn-scrap-report-export').click();
        const download = await downloadEvent;
        const file = path.join(output, 'scrap.csv');
        await download.saveAs(file);
        const csv = fs.readFileSync(file);
        assert.equal(csv.subarray(0, 3).toString('hex'), 'efbbbf');
        assert.match(csv.toString('utf8'), /علت ساختگی/);
        assert.match(csv.toString('utf8'), /بایگانی‌شده/);
        assert.equal(csv.toString('utf8').trim().split('\r\n').length, 3);
        await page.screenshot({ path: path.join(output, 'report-desktop.png'), fullPage: true });
        // The admin jump dialog already occupies the nested modal: collecting a reason must still work.
        const adminPiece = await page.evaluate(async id => {
            const original = await PieceAPI.getById(id);
            const p = await PieceAPI.create({ pieceDefinitionId: original.pieceDefinitionId, pieceNumber: 3 });
            await openPieceProfile(p.id); return p.id;
        }, process.env.SCRAP_PIECE);
        await page.locator('#btn-admin-jump').click();
        await page.locator('#admin-jump-stage').selectOption('SCRAPPED');
        await page.locator('#btn-confirm-admin-jump').click();
        await page.locator('#scrap-type').selectOption('CR');
        await page.locator('#form-scrap-reason button[type=submit]').click();
        await page.locator('#btn-edit-scrap').waitFor();
        assert.equal((await page.evaluate(id => PieceAPI.getScrapDispatches(id), adminPiece))[0].defectType, 'CR');
        // Tensile disposition must collect its own reason, not rely on its optional general notes.
        const tensile = await page.evaluate(async id => {
            const original = await PieceAPI.getById(id);
            let p = await PieceAPI.create({ pieceDefinitionId: original.pieceDefinitionId, pieceNumber: 4 });
            p = await PieceAPI.updateStage(p.id, 'TENSILE');
            const test = await TensileTestAPI.create(p.id, { samples: [{ uts: 100 }] });
            await openTensileDispositionModal(p, test.id);
            TensileState.dispositionDateIso = '2026-10-31';
            return { pieceId: p.id, testId: test.id };
        }, process.env.SCRAP_PIECE);
        await page.locator('#disposition-next-stage').selectOption('SCRAP');
        await page.locator('#disposition-inspection').selectOption('REJECTED');
        await page.locator('#form-tensile-disposition button[type=submit]').click();
        await page.locator('#scrap-type').selectOption('OTHER');
        await page.locator('#scrap-custom').fill('علت کشش ساختگی');
        const dispositionResponse = page.waitForResponse(r => r.url().endsWith('/disposition') && r.request().method() === 'PUT');
        await page.locator('#form-scrap-reason button[type=submit]').click();
        assert.equal((await dispositionResponse).status(), 200);
        assert.equal((await page.evaluate(id => PieceAPI.getScrapDispatches(id), tensile.pieceId))[0].defectTypeCustom, 'علت کشش ساختگی');
        assert.deepEqual(errors, []);
        console.log('Scrap browser passed: reason catalog/Other, optional notes, cancel, edit, unchanged timestamp, archived/legacy report, CSV, admin jump, tensile, desktop/mobile.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
