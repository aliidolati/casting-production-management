'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {chromium}=require('playwright');
const base=process.env.SECURITY_BASE;
assert.match(base,/^http:\/\/127\.0\.0\.1:\d+$/);
const output=path.resolve('target/security-browser');fs.mkdirSync(output,{recursive:true});
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const errors=[];
 async function session(username,password){
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage();page.setDefaultTimeout(15000);
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.locator('#input-login-username').fill(username);
  await page.locator('#input-login-password').fill(password);
  await page.locator('#form-login button[type=submit]').click();
  await page.locator('#app-shell').waitFor({state:'visible'});return page;
 }
 try {
  const catalog=await session(process.env.SECURITY_CATALOG,process.env.SECURITY_PASSWORD);
  const nonce=crypto.randomBytes(4).toString('hex');
  const payload=kind=>'SEC-'+nonce+'"><img id="injected-'+kind+'" src="/synthetic-missing-image" onerror="window.__storedXss=1"><input value="';
  const code=payload('code'),name=payload('name'),pieceName=payload('piece');
  const fixture=await catalog.evaluate(async data=>{
   const p=await ProjectAPI.create({code:data.code,name:data.name});
   const d=await PieceDefinitionAPI.create({projectId:p.id,rowNum:1,pieceName:data.pieceName});
   return {project:p.id,definition:d.id};
  },{code,name,pieceName});
  const admin=await session(process.env.SECURITY_ADMIN,process.env.SECURITY_PASSWORD);
  await admin.locator('.nav-btn[data-section="projects"]').click();
  await admin.locator('tr[data-project-id="'+fixture.project+'"] .btn-edit-project').click();
  await admin.waitForTimeout(200);
  assert.equal(await admin.locator('#input-edit-project-code').inputValue(),code);
  assert.equal(await admin.locator('#input-edit-project-name').inputValue(),name);
  assert.equal(await admin.locator('#modal-body img[id^="injected-"]').count(),0);
  assert.equal(await admin.evaluate(()=>window.__storedXss||0),0);
  await admin.locator('#input-edit-project-code').fill('SEC-'+nonce);
  const editedProject='نام ویرایش‌شده " & <متن>';
  await admin.locator('#input-edit-project-name').fill(editedProject);
  await admin.locator('#form-edit-project button[type=submit]').click();
  await admin.locator('#form-edit-project').waitFor({state:'detached'});
  assert.equal(await admin.evaluate(id=>ProjectAPI.getById(id).then(p=>p.name),fixture.project),editedProject);
  await admin.locator('tr[data-project-id="'+fixture.project+'"]').click();
  await admin.locator('tr[data-definition-id="'+fixture.definition+'"] .btn-edit-definition').click();
  await admin.waitForTimeout(200);
  assert.equal(await admin.locator('#input-edit-piece-name').inputValue(),pieceName);
  assert.equal(await admin.locator('#modal-body img[id^="injected-"]').count(),0);
  assert.equal(await admin.evaluate(()=>window.__storedXss||0),0);
  await admin.screenshot({path:path.join(output,'catalog-desktop.png'),fullPage:true});
  await admin.setViewportSize({width:390,height:844});
  assert.equal(await admin.locator('#input-edit-piece-name').inputValue(),pieceName);
  assert.equal(await admin.evaluate(()=>window.__storedXss||0),0);
  await admin.screenshot({path:path.join(output,'catalog-mobile.png'),fullPage:true});
  const editedPiece='قطعهٔ ویرایش‌شده " & <متن>';
  await admin.locator('#input-edit-piece-name').fill(editedPiece);
  await admin.locator('#form-edit-definition button[type=submit]').click();
  await admin.locator('#form-edit-definition').waitFor({state:'detached'});
  assert.equal(await admin.evaluate(id=>PieceDefinitionAPI.getById(id).then(d=>d.pieceName),fixture.definition),editedPiece);
  const catalogId=await catalog.evaluate(()=>AuthState.user.id);
  await catalog.locator('#btn-change-password').click();
  await catalog.locator('#input-current-password').fill(process.env.SECURITY_PASSWORD);
  await catalog.locator('#input-new-password').fill(process.env.SECURITY_PASSWORD+'-changed');
  await catalog.locator('#input-confirm-password').fill(process.env.SECURITY_PASSWORD+'-changed');
  await catalog.locator('#form-change-password button[type=submit]').click();
  await catalog.locator('#login-screen').waitFor({state:'visible'});
  assert.equal(await catalog.evaluate(()=>localStorage.getItem(AUTH_TOKEN_KEY)),null);
  await catalog.locator('#input-login-username').fill(process.env.SECURITY_CATALOG);
  await catalog.locator('#input-login-password').fill(process.env.SECURITY_PASSWORD+'-changed');
  await catalog.locator('#form-login button[type=submit]').click();
  await catalog.locator('#app-shell').waitFor({state:'visible'});
  await admin.evaluate(({id,pwd})=>UserAPI.resetPassword(id,pwd),{id:catalogId,pwd:process.env.SECURITY_PASSWORD+'-admin-reset'});
  await catalog.evaluate(async()=>{try{await AuthAPI.me();}catch{}});
  await catalog.locator('#login-screen').waitFor({state:'visible'});
  assert.equal(await catalog.evaluate(()=>localStorage.getItem(AUTH_TOKEN_KEY)),null);
  assert.deepEqual(errors,[]);
  console.log('PASS: stored project code/name and piece name do not execute; edits round-trip; desktop/mobile; expired credential session requires login.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
